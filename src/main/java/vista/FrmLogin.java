    private void btnAccesoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAccesoActionPerformed
        String usuario = txtUsuario.getText().trim();
        String clave = String.valueOf(txtClave.getPassword());

        if (usuario.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese el usuario.");
            txtUsuario.requestFocus();
            return;
        }

        if (clave.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese la contraseña.");
            txtClave.requestFocus();
            return;
        }

        Usuario u = servicio.login(usuario, clave);

        if (u != null) {
            if (!u.getActivo().equalsIgnoreCase("Activo")) {
                JOptionPane.showMessageDialog(this,"El usuario se encuentra deshabilitado.");
                return;
            }
            
            JOptionPane.showMessageDialog(this, "Bienvenido " + u.getEmpleado().getNombres() + " " + u.getEmpleado().getApellidos());

            this.dispose();
            Principal frm = new Principal(u);
            frm.setLocationRelativeTo(null);
            frm.setVisible(true);
        } else {
            JOptionPane.showMessageDialog(this,"Usuario o contraseña incorrectos.");
          
            txtClave.setText("");
            txtClave.requestFocus();
        }
    }//GEN-LAST:event_btnAccesoActionPerformed

